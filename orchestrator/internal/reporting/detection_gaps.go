package reporting

import (
	"context"
	"fmt"

	"github.com/audspect/bas/internal/detectgap"
	"github.com/audspect/bas/internal/models"
	"github.com/audspect/bas/internal/rulelib"
	"github.com/audspect/bas/internal/verification"
)

const (
	// gapReportRules is how many rules the report shows per gap. The console and the zip export carry the rest.
	gapReportRules = 1
	// gapReportQueryChars caps a query in the report; the full text is in the export.
	gapReportQueryChars = 1200
)

// DetectionGapSection is the report's Detection Engineering Recommendations. It is built from the same
// detectgap.Assess the console and the export use, so the three cannot disagree. It only exists when the run has at
// least one technique that executed and was reviewed as not detected.
type DetectionGapSection struct {
	HasData     bool           `json:"hasData"`
	Assessed    int            `json:"assessed"`
	Gaps        int            `json:"gaps"`
	Summary     map[string]int `json:"summary"`
	Rows        []GapRow       `json:"rows"`
	Attribution string         `json:"attribution"`
}

type GapRow struct {
	TechniqueID   string       `json:"techniqueId"`
	Name          string       `json:"name"`
	Reason        string       `json:"reason"`
	Availability  string       `json:"availability"`
	Effectiveness string       `json:"effectiveness"`
	RuleCount     int          `json:"ruleCount"`
	Rules         []GapRuleRow `json:"rules"`
}

type GapRuleRow struct {
	ID       string     `json:"id"`
	Title    string     `json:"title"`
	Severity string     `json:"severity"`
	Match    string     `json:"match"` // exact | parent
	Source   string     `json:"source"`
	Queries  []GapQuery `json:"queries"`
}

type GapQuery struct {
	Backend    string `json:"backend"`
	Language   string `json:"language"`
	Query      string `json:"query"`
	Truncated  bool   `json:"truncated"`
	Mapping    string `json:"mapping"`
	DataSource string `json:"dataSource"`
	Note       string `json:"note"`
}

// BuildDetectionGaps turns a run's results, its current reviewed verifications and the rule library into the report
// section. A nil rules resolver or a run with no reviewed gap yields an empty section (HasData false): the report
// renders exactly as before.
func BuildDetectionGaps(results []models.SimulationResult, current map[string]verification.Record, rules RuleLibraryResolver) DetectionGapSection {
	sec := DetectionGapSection{Summary: map[string]int{}}
	assessments := detectgap.Assess(results, current)
	sec.Assessed = len(assessments)
	for _, a := range assessments {
		sec.Summary[string(a.Status)]++
		if a.Status != detectgap.DetectionGap {
			continue
		}
		sec.Gaps++
		found, match := lookupRules(rules, a.TechniqueID)
		row := GapRow{
			TechniqueID: a.TechniqueID, Name: a.Name, Reason: a.Reason,
			Availability: detectgap.Availability(found, ""), Effectiveness: detectgap.Effectiveness, RuleCount: len(found),
		}
		for _, r := range detectgap.PickRules(found, "", gapReportRules) {
			rr := GapRuleRow{ID: r.ID, Title: r.Title, Severity: r.Severity, Match: match,
				Source: fmt.Sprintf("%s %s (%s)", r.Source.Name, shortCommit(r.Source.Commit), r.Source.License)}
			for _, t := range r.Translations {
				q := GapQuery{Backend: detectgap.BackendLabel(t.Backend), Language: t.Language, Query: t.Query,
					Mapping: t.Mapping, DataSource: t.DataSource, Note: detectgap.QueryNote(t.Mapping, t.DataSource)}
				if len(q.Query) > gapReportQueryChars {
					q.Query, q.Truncated = q.Query[:gapReportQueryChars], true
				}
				rr.Queries = append(rr.Queries, q)
			}
			row.Rules = append(row.Rules, rr)
			sec.Attribution = "Detection rules: SigmaHQ (github.com/SigmaHQ/sigma), Detection Rule License (DRL) 1.1. Each rule keeps its original author. " +
				"Translations to SIEM queries are generated by Audspect and are not validated against a live SIEM."
		}
		sec.Rows = append(sec.Rows, row)
	}
	sec.HasData = sec.Gaps > 0
	if !sec.HasData {
		return DetectionGapSection{}
	}
	return sec
}

// lookupRules mirrors the console: the rules tagged with the technique, else those tagged only with its parent
// (labelled "parent": broader, never presented as exact).
func lookupRules(rules RuleLibraryResolver, techniqueID string) (found []rulelib.Rule, match string) {
	if rules == nil {
		return nil, ""
	}
	if rs := rules.RulesByTechnique(techniqueID); len(rs) > 0 {
		return rs, "exact"
	}
	for i := 0; i < len(techniqueID); i++ {
		if techniqueID[i] == '.' {
			if rs := rules.RulesByTechnique(techniqueID[:i]); len(rs) > 0 {
				return rs, "parent"
			}
			break
		}
	}
	return nil, ""
}

func shortCommit(c string) string {
	if len(c) > 8 {
		return c[:8]
	}
	return c
}

// buildDetectionGaps attaches the run's verifications and the rule library; both stay optional.
func (e *Engine) buildDetectionGaps(ctx context.Context, runID string, results []models.SimulationResult) DetectionGapSection {
	if e.rules == nil || runID == "" || e.verifications == nil {
		return DetectionGapSection{}
	}
	current, err := e.verifications.CurrentForRun(ctx, runID)
	if err != nil {
		return DetectionGapSection{}
	}
	return BuildDetectionGaps(results, current, e.rules)
}
