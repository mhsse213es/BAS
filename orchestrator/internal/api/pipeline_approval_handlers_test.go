// approvalRouter mounts the production router with the given startup deployment class.
func approvalRouter(pool *pgxpool.Pool, c injectionapproval.Classification, t *testing.T) http.Handler {
	t.Helper()
	h := New(pool, ws.NewHub(), scenario.NewEngine(t.TempDir()), testJWTSecret).WithDeploymentClass(c)
	return Mount(h, ws.NewHub(), testJWTSecret, "", http.NotFoundHandler(), 0, 0)
}

func doRoute(t *testing.T, router http.Handler, method, path, body string, role auth.Role, user string) *httptest.ResponseRecorder {
	t.Helper()
	var rdr *strings.Reader
	if body != "" {
		rdr = strings.NewReader(body)
	} else {
		rdr = strings.NewReader("")
	}
	req := authedRequest(t, method, path, rdr, role, user)
	rec := httptest.NewRecorder()
	router.ServeHTTP(rec, req)
	return rec
}

const createInjectionBody = `{"kind":"injection","campaignId":"c1","stageKey":"inject","connectorId":"dc-elastic",
	"index":"logs-bas","document":{"event":{"action":"probe"}},"testScope":"one record",
	"expectedChange":"record searchable by run identifier"}`

// requestInjection creates an injection approval request as an admin and returns its ID and run ID.
func requestInjection(t *testing.T, router http.Handler, user string) (string, string) {
	t.Helper()
	rec := doRoute(t, router, http.MethodPost, "/api/pipeline-approvals", createInjectionBody, auth.RoleAdmin, user)
	if rec.Code != http.StatusOK {
		t.Fatalf("create: status %d body %s", rec.Code, rec.Body.String())
	}
	var out struct {
		ApprovalID string `json:"approvalId"`
		RunID      string `json:"runId"`
	}
	if err := json.Unmarshal(rec.Body.Bytes(), &out); err != nil {
		t.Fatal(err)
	}
	return out.ApprovalID, out.RunID
}

// Only a user with the approval permission may request, read or decide an approval.
func TestPipelineApprovalRoutes_RoleGating(t *testing.T) {
	sharedDB.RunWithPool(t, func(pool *pgxpool.Pool) {
		router := approvalRouter(pool, injectionapproval.Customer, t)
		if rec := doRoute(t, router, http.MethodPost, "/api/pipeline-approvals", createInjectionBody, auth.RoleAnalyst, "alice"); rec.Code != http.StatusForbidden {
			t.Fatalf("analyst create: status %d, want 403", rec.Code)
		}
		id, _ := requestInjection(t, router, "admin-1")
		if rec := doRoute(t, router, http.MethodGet, "/api/pipeline-approvals/"+id, "", auth.RoleAnalyst, "alice"); rec.Code != http.StatusForbidden {
			t.Fatalf("analyst read: status %d, want 403", rec.Code)
		}
		if rec := doRoute(t, router, http.MethodPost, "/api/pipeline-approvals/"+id+"/approve", "", auth.RoleAnalyst, "alice"); rec.Code != http.StatusForbidden {
			t.Fatalf("analyst approve: status %d, want 403", rec.Code)
		}
	})
}

// Unauthenticated requests are refused.
func TestPipelineApprovalRoutes_UnauthenticatedRefused(t *testing.T) {
	sharedDB.RunWithPool(t, func(pool *pgxpool.Pool) {
		router := approvalRouter(pool, injectionapproval.Customer, t)
		req := httptest.NewRequest(http.MethodPost, "/api/pipeline-approvals", strings.NewReader(createInjectionBody))
		rec := httptest.NewRecorder()
		router.ServeHTTP(rec, req)
		if rec.Code != http.StatusUnauthorized && rec.Code != http.StatusForbidden {
			t.Fatalf("anonymous create: status %d, want 401 or 403", rec.Code)
		}
	})
}

// The caller cannot supply a run identifier, a payload hash, or a deployment class. Each one is an
// unknown field and the request is refused.
func TestPipelineApprovalRoutes_CallerCannotSetRunOrClass(t *testing.T) {
	sharedDB.RunWithPool(t, func(pool *pgxpool.Pool) {
		router := approvalRouter(pool, injectionapproval.Customer, t)
		for _, field := range []string{`"runId":"bas-0123456789abcdef0123456789abcdef"`, `"payloadHash":"sha256:x"`, `"deploymentClass":"lab"`} {
			body := strings.Replace(createInjectionBody, `"kind":"injection",`, `"kind":"injection",`+field+`,`, 1)
			if rec := doRoute(t, router, http.MethodPost, "/api/pipeline-approvals", body, auth.RoleAdmin, "admin-1"); rec.Code != http.StatusBadRequest {
				t.Fatalf("caller field %s: status %d, want 400", field, rec.Code)
			}
		}
	})
}

// The run identifier is generated by the server and the stored scope carries the tagged payload,
// so the approver sees exactly what will be written.
func TestPipelineApprovalRoutes_ServerGeneratesRunAndScopeShowsPayload(t *testing.T) {
	sharedDB.RunWithPool(t, func(pool *pgxpool.Pool) {
		router := approvalRouter(pool, injectionapproval.Customer, t)
		id, runID := requestInjection(t, router, "admin-1")
		if !strings.HasPrefix(runID, "bas-") || len(runID) != 36 {
			t.Fatalf("run id %q is not server-generated", runID)
		}
		rec := doRoute(t, router, http.MethodGet, "/api/pipeline-approvals/"+id, "", auth.RoleAdmin, "admin-2")
		if rec.Code != http.StatusOK {
			t.Fatalf("read: status %d", rec.Code)
		}
		var view struct {
			Scope struct {
				Target  string `json:"Target"`
				Payload string `json:"Payload"`
			} `json:"scope"`
			Status string `json:"status"`
		}
		if err := json.Unmarshal(rec.Body.Bytes(), &view); err != nil {
			t.Fatal(err)
		}
		if view.Scope.Target != "logs-bas" || !strings.Contains(view.Scope.Payload, runID) || !strings.Contains(view.Scope.Payload, `"test_run"`) {
			t.Fatalf("scope does not show the tagged payload: %+v", view.Scope)
		}
	})
}

// Customer deployment: the requester cannot approve their own request. A different admin can.
// A decided request cannot be decided again.
func TestPipelineApprovalRoutes_CustomerApprovalRules(t *testing.T) {
	sharedDB.RunWithPool(t, func(pool *pgxpool.Pool) {
		router := approvalRouter(pool, injectionapproval.Customer, t)
		id, _ := requestInjection(t, router, "admin-1")
		if rec := doRoute(t, router, http.MethodPost, "/api/pipeline-approvals/"+id+"/approve", "", auth.RoleAdmin, "admin-1"); rec.Code != http.StatusForbidden {
			t.Fatalf("self-approval: status %d, want 403", rec.Code)
		}
		if rec := doRoute(t, router, http.MethodPost, "/api/pipeline-approvals/"+id+"/approve", "", auth.RoleAdmin, "admin-2"); rec.Code != http.StatusOK {
			t.Fatalf("second admin approve: status %d body %s", rec.Code, rec.Body.String())
		}
		if rec := doRoute(t, router, http.MethodPost, "/api/pipeline-approvals/"+id+"/approve", "", auth.RoleAdmin, "admin-3"); rec.Code != http.StatusConflict {
			t.Fatalf("approve again: status %d, want 409", rec.Code)
		}
		if rec := doRoute(t, router, http.MethodPost, "/api/pipeline-approvals/"+id+"/refuse", `{"reason":"changed mind"}`, auth.RoleAdmin, "admin-3"); rec.Code != http.StatusConflict {
			t.Fatalf("refuse after approval: status %d, want 409 (approval is not revoked by refusal)", rec.Code)
		}
	})
}

