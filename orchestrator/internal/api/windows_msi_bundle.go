const (
	// windowsMSIFile is the generic, signed MSI as staged in the agents directory and
	// listed in the signed integrity manifest.
	windowsMSIFile = "AudspectAgent-x64.msi"
)

// agentArtifactDir is where agent artifacts live. A variable so tests can point it elsewhere.
var agentArtifactDir = "./agents"

var fingerprintRe = regexp.MustCompile(`^[0-9a-f]{64}$`)

// serveWindowsMSI builds the per-request Windows agent bundle: the single generic MSI
// (verified against the signed manifest, never modified), a freshly signed
// deployment.json, and install scripts that pass the signing fingerprint explicitly.
// The agent secret is never part of it.
//
// It fails closed: with no signing key, no loaded manifest, or an MSI that is missing,
// unlisted or does not match its manifest hash, nothing is served.
func (h *Handler) serveWindowsMSI(w http.ResponseWriter, r *http.Request) {
	if h.signingKey == nil {
		jsonError(w, "no signing key is configured on this server", http.StatusServiceUnavailable)
		return
	}
	if h.manifest == nil || !h.manifest.Loaded() {
		jsonError(w, "the integrity manifest is not loaded, so the installer cannot be verified", http.StatusServiceUnavailable)
		return
	}
	msi, err := os.ReadFile(filepath.Join(agentArtifactDir, windowsMSIFile))
	if err != nil {
		jsonError(w, "the Windows MSI is not available on this server", http.StatusNotFound)
		return
	}
	want, listed := h.manifest.KnownHash(windowsMSIFile)
	sum := sha256.Sum256(msi)
	if !listed || hex.EncodeToString(sum[:]) != want {
		log.Printf("[!!] TAMPER: %q is not listed in, or does not match, the signed manifest -- refusing to serve", windowsMSIFile)
		jsonError(w, "agent installer failed integrity verification", http.StatusInternalServerError)
		return
	}

	cfg := deployconfig.Config{
		ServerURL:  "https://" + requestHost(r) + ":" + portOrDefault(h.advertisedMTLSPort, "9443"),
		EnrollPort: portOrDefault(h.advertisedEnrollPort, "9444"),
		IssuedAt:   time.Now().UTC(),
	}
	if h.pki != nil {
		cfg.CARootPEM = string(h.pki.RootCertPEM())
	}
	env, err := deployconfig.Build(h.signingKey, cfg)
	if err != nil {
		jsonError(w, "could not build the deployment configuration: "+err.Error(), http.StatusInternalServerError)
		return
	}
	fp, err := deployconfig.Fingerprint(h.signingKey.CertPEM())
	if err != nil {
		jsonError(w, "could not compute the signing fingerprint: "+err.Error(), http.StatusInternalServerError)
		return
	}
	bundle, err := buildMSIBundle(msi, env, fp)
	if err != nil {
		jsonError(w, "could not build the installer bundle: "+err.Error(), http.StatusInternalServerError)
		return
	}
	if h.db != nil {
		h.auditLog(r, "agent.download_msi", "windows-amd64-msi", map[string]any{"fingerprint": fp}, "ok")
	}
	w.Header().Set("Content-Type", "application/zip")
	w.Header().Set("Content-Disposition", `attachment; filename="AudspectAgent-x64.zip"`)
	w.Header().Set("Cache-Control", "no-store")
	w.Write(bundle)
}

// buildMSIBundle zips the MSI, the signed deployment config and the install scripts.
// The fingerprint is embedded in scripts, so it must be exactly 64 lowercase hex characters.
func buildMSIBundle(msi, deploymentJSON []byte, fingerprint string) ([]byte, error) {
	if !fingerprintRe.MatchString(fingerprint) {
		return nil, fmt.Errorf("fingerprint must be 64 lowercase hex characters")
	}
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	add := func(name string, data []byte) error {
		f, err := zw.Create(name)
		if err != nil {
			return err
		}
		_, err = io.Copy(f, bytes.NewReader(data))
		return err
	}
	files := []struct {
		name string
		data []byte
	}{
		{windowsMSIFile, msi},
		{"deployment.json", deploymentJSON},
		{"install.cmd", []byte(installCmd)},
		{"install.ps1", []byte(strings.ReplaceAll(installPs1, "__FINGERPRINT__", fingerprint))},
		{"README.txt", []byte(strings.ReplaceAll(readmeTxt, "__FINGERPRINT__", fingerprint))},
	}
	for _, f := range files {
		if err := add(f.name, f.data); err != nil {
			return nil, err
		}
	}
	if err := zw.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

const installCmd = "@echo off\r\n" +
	"rem Silent install of the Audspect Agent. Run from an elevated prompt.\r\n" +
	"powershell.exe -NoProfile -ExecutionPolicy Bypass -File \"%~dp0install.ps1\"\r\n" +
	"exit /b %ERRORLEVEL%\r\n"

const installPs1 = `# Audspect Agent silent install (generated by the Audspect server).
# The agent secret is typed here, kept only in this process's environment for msiexec, and never
# written to a file, a command line or a log.
param([string]$ConfigFingerprint = '__FINGERPRINT__')
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path

Write-Host 'Audspect Agent silent install'
Write-Host 'Deployment signing key fingerprint embedded in this script:'
Write-Host ('  ' + $ConfigFingerprint)
Write-Host 'Compare it with the fingerprint shown in the Audspect dashboard. Anyone who replaces this'
Write-Host 'download can also replace the line above, so check it against the dashboard, not this folder.'
$answer = Read-Host 'Type YES if it matches'
if ($answer -ne 'YES') { Write-Host 'Cancelled.'; exit 1 }

$secure = Read-Host 'Agent secret' -AsSecureString
$bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
try { $env:AUDSPECT_AGENT_SECRET = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr) }
finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr) }

try {
    $msi = Join-Path $here 'AudspectAgent-x64.msi'
    $log = Join-Path $here 'install.log'
    $p = Start-Process -FilePath msiexec.exe -Wait -PassThru -ArgumentList @(
        '/i', ('"' + $msi + '"'), '/qn', '/l*v', ('"' + $log + '"'),
        ('CONFIG_FINGERPRINT=' + $ConfigFingerprint))
    Write-Host ('msiexec exit code: ' + $p.ExitCode + '  (log: ' + $log + ')')
    exit $p.ExitCode
}
finally { Remove-Item Env:AUDSPECT_AGENT_SECRET -ErrorAction SilentlyContinue }
`

